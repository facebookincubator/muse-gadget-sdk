"""The musegadgets BLE voice codecs: SBC (xplat/libsbc) and LC3 (xplat/liblc3,
and its fixed-point port xplat/lc3fx) through the
firmware's encoder wrapper, decoded back with the vendored decoders; lc3fx and
liblc3 decoding each other's streams; and the SBC stream with FFmpeg's decoder
when it's installed."""

