from test_mg_ble import MG, PROTOCOLS, ROOT, codec_build, compile_and_run, lc3_build


def best_snr(ref: array.array, out: array.array) -> float:
    best = -100.0
    for lag in range(0, 400):
        sig = err = 0.0
        for i in range(2000, min(len(ref), len(out) - lag), 3):
            d = out[i + lag] - ref[i]
            sig += ref[i] * ref[i]
            err += d * d
        best = max(best, 10 * math.log10(sig / (err + 1e-9)))
    return best


class MgCodecsTest(unittest.TestCase):
    def test_round_trip(self) -> None:
        srcs, defs, incs = codec_build(True)
        with tempfile.TemporaryDirectory(prefix="mg-codec-") as tmp:
            out = compile_and_run(
                self, [ROOT / "tests/mg_codec_harness.c", MG / "mg_codec.c"], defs,
                [MG, PROTOCOLS, *incs], vendor=srcs,
                args=[str(Path(tmp) / "voice.sbc")], cwd=Path(tmp))
            self.assertIn("PASS mg_codec", out)
            snr = {m[0]: float(m[1]) for m in re.findall(r"SNR (\w+) (-?[\d.]+)", out)}
            # Waveform SNR of a voiced signal; the perceptual numbers are in the READMEs.
            self.assertGreater(snr["sbc"], 20.0, out)
            self.assertGreater(snr["lc3"], 12.0, out)

            ffmpeg = shutil.which("ffmpeg")
            probe = subprocess.run([ffmpeg, "-hide_banner", "-decoders"], capture_output=True, text=True) \
                if ffmpeg else None
            if not probe or probe.returncode != 0 or not re.search(r"^ A\S* sbc ", probe.stdout, re.M):
                return  # no working FFmpeg with an SBC decoder here
            dec = Path(tmp) / "ffmpeg.raw"
            r = subprocess.run([ffmpeg, "-v", "error", "-y", "-f", "sbc", "-i", str(Path(tmp) / "voice.sbc"),
                                "-f", "s16le", "-ac", "1", "-ar", "16000", str(dec)],
                               capture_output=True, text=True)
            self.assertEqual(r.returncode, 0, r.stderr)
            ref = array.array("h", (Path(tmp) / "input.raw").read_bytes())
            got = array.array("h", dec.read_bytes())
            self.assertGreater(best_snr(ref, got), 12.0, "FFmpeg decodes the SBC stream")

    def test_liblc3_rates(self) -> None:
        # liblc3 as the SDKs build it codes 10 ms frames at 16 and
        # 24 kHz (tables.c regenerated by xplat/liblc3/tools/trim_tables.py)
        # and refuses every other rate at setup, never touching a NULL table.
        for fixed in (False, True):   # liblc3 and lc3fx (the C3, C6 and Mosaico)
            with self.subTest(lc3fx=fixed):
                srcs, defs, incs = lc3_build(fixed)
                self.assertIn("LC3_SR_MASK=6", defs)
                with tempfile.TemporaryDirectory(prefix="mg-lc3-rates-") as tmp:
                    out = compile_and_run(self, [ROOT / "tests/lc3_rates_harness.c"], defs, incs, vendor=srcs,
                                          cwd=Path(tmp))
                snr = {(int(r), int(k)): float(v) for r, k, v in re.findall(r"rate (\d+) kbps (\d+) snr (-?[\d.]+)", out)}
                self.assertEqual(len(snr), 4, out)
                for (rate, kbps), v in snr.items():
                    self.assertGreater(v, 8.0, f"{rate} Hz {kbps} kb/s: {out}")
                self.assertGreaterEqual(snr[(24000, 48)], snr[(24000, 24)], out)
                self.assertEqual(re.findall(r"refused (\d+) (\d)", out), [("8000", "1"), ("32000", "1"), ("48000", "1")], out)
        # The generator documents itself and reproduces the 16 kHz-only trim (checked by hand
        # against upstream 8e1e722; upstream isn't vendored).
        gen = (ROOT.parent / "xplat/liblc3/tools/trim_tables.py").read_text()
        self.assertIn("def needed_sizes(rates)", gen)
        self.assertIn("generated for 16 kHz / 24 kHz, 10 ms only", (ROOT.parent / "xplat/liblc3/src/tables.c").read_text()[:2000])

    def test_round_trip_fixed_point_lc3(self) -> None:
        srcs, defs, incs = codec_build(True, fixed=True)
        with tempfile.TemporaryDirectory(prefix="mg-codec-") as tmp:
            out = compile_and_run(
                self, [ROOT / "tests/mg_codec_harness.c", MG / "mg_codec.c"], defs,
                [MG, PROTOCOLS, *incs], vendor=srcs,
                args=[str(Path(tmp) / "voice.sbc")], cwd=Path(tmp))
            self.assertIn("PASS mg_codec", out)
            snr = {m[0]: float(m[1]) for m in re.findall(r"SNR (\w+) (-?[\d.]+)", out)}
            self.assertGreater(snr["lc3"], 12.0, out)

    def _tool(self, tmp: Path, fixed: bool) -> Path:
        cc = shlex.split(os.environ.get("CC", "cc"))
        if not cc or shutil.which(cc[0]) is None:
            self.skipTest("C compiler not available")
        srcs, defs, incs = lc3_build(fixed)
        exe = tmp / ("lc3fx" if fixed else "liblc3")
        cmd = [*cc, "-std=c11", "-D_DEFAULT_SOURCE", "-O2", "-w", *[f"-D{d}" for d in defs], *sum((["-I", str(i)] for i in incs), []),
               str(ROOT / "tests/lc3_interop_tool.c"), *map(str, srcs), "-lm", "-o", str(exe)]
        r = subprocess.run(cmd, text=True, capture_output=True)
        self.assertEqual(r.returncode, 0, r.stdout + r.stderr)
        return exe

    def test_lc3fx_and_liblc3_interoperate(self) -> None:
        # Each decodes the other's stream (chips with and without an
        # FPU talk the same LC3), and lc3fx's decoder stays within a few LSB
        # of liblc3's on the same frames; at 16 and 24 kHz.
        with tempfile.TemporaryDirectory(prefix="mg-lc3-") as name:
            tmp = Path(name)
            fx, flt = self._tool(tmp, True), self._tool(tmp, False)
            for rate in (16000, 24000):
                with self.subTest(rate=rate):
                    self._interop(tmp, fx, flt, rate)

    def _interop(self, tmp: Path, fx: Path, flt: Path, rate: int) -> None:
        pcm = array.array("h")
        for i in range(rate * 2):   # 2 s: two tones and a pitch glide, voice level (+ 9.5 kHz at 24 kHz)
            t = i / rate
            v = 0.25 * math.sin(2 * math.pi * 220 * t) + 0.12 * math.sin(2 * math.pi * 1250 * t) \
                + 0.1 * math.sin(2 * math.pi * (300 + 400 * t) * t)
            if rate > 16000:
                v += 0.05 * math.sin(2 * math.pi * 9500 * t)
            pcm.append(int(v * 32767 * (0.5 + 0.5 * math.sin(2 * math.pi * 1.5 * t))))
        raw = tmp / f"in{rate}.raw"
        raw.write_bytes(pcm.tobytes())

        def run(exe: Path, mode: str, src: Path, dst: Path) -> None:
            r = subprocess.run([str(exe), mode, str(src), str(dst), str(rate)], text=True, capture_output=True)
            self.assertEqual(r.returncode, 0, r.stdout + r.stderr)
            self.assertIn("200 frames", r.stdout)

        run(fx, "enc", raw, tmp / "fx.lc3")
        run(flt, "enc", raw, tmp / "flt.lc3")
        for enc in ("fx", "flt"):
            for dec, exe in (("fx", fx), ("flt", flt)):
                run(exe, "dec", tmp / f"{enc}.lc3", tmp / f"{enc}_{dec}.raw")
        for enc in ("fx", "flt"):
            for dec in ("fx", "flt"):
                with self.subTest(encoder=enc, decoder=dec):
                    got = array.array("h", (tmp / f"{enc}_{dec}.raw").read_bytes())
                    self.assertGreater(best_snr(pcm, got), 12.0)
        # Same frames, both decoders: lc3fx's within a few LSB of liblc3's.
        for enc in ("fx", "flt"):
            a = array.array("h", (tmp / f"{enc}_fx.raw").read_bytes())
            b = array.array("h", (tmp / f"{enc}_flt.raw").read_bytes())
            self.assertEqual(len(a), len(b))
            worst = max(abs(x - y) for x, y in zip(a, b))
            self.assertLessEqual(worst, 8, f"{rate} Hz, {enc} stream: decoders differ by {worst} LSB")

