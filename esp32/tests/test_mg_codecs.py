    def test_lc3fx_is_the_vendored_copy(self) -> None:
        # VENDORED.md lists the SHA-256 of every xplat/lc3fx file but README.md: a file added, removed or
        # edited here fails until the note is updated with it.
        d = ROOT.parent / "xplat/lc3fx"
        note = (d / "VENDORED.md").read_text()
        want = dict((name, h) for h, name in re.findall(r"^([0-9a-f]{64})  (\S+)$", note, re.M))
        ours = sorted(p.relative_to(d).as_posix() for p in d.rglob("*")
                      if p.is_file() and p.name != "VENDORED.md" and p.relative_to(d).as_posix() != "README.md")
        self.assertEqual(ours, sorted(want))
        for rel in ours:
            got = hashlib.sha256((d / rel).read_bytes()).hexdigest()
            self.assertEqual(got, want[rel], f"{rel} changed since it was vendored ({got})")


