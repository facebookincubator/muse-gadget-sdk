"""Regenerate the caption font's colour emoji (CONFIG_MUSE_EMOJI).

Writes components/muse/fonts/muse_font_emoji_16.c, an LVGL font whose glyphs
are 16x16 RGB565A8 images, the height of the caption font (unscii-16), and
components/muse/fonts/muse_emoji.h, the code points it has, which muse_text.c
keeps in captions. The images are Twemoji's 72x72 PNGs (jdecked/twemoji
v16.0.1, graphics under CC-BY 4.0), scaled down to 16 px.

Usage: gen_emoji_font.py [TWEMOJI_DIR]   (requires Pillow)

Without TWEMOJI_DIR it downloads the pinned release and checks its SHA-256.
To change the set, edit EMOJI below and run it again.
"""

