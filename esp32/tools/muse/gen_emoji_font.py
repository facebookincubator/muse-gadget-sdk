LICENSE_NOTE = """\
/*
 * Generated by tools/muse/gen_emoji_font.py; do not edit.
 *
 * Twemoji graphics by Twitter, Inc and other contributors, and Jason Sofonia,
 * Justine De Caires and other contributors (https://github.com/jdecked/twemoji,
 * v{version}), licensed under CC-BY 4.0
 * (https://creativecommons.org/licenses/by/4.0/, see LICENSE-twemoji.txt).
 * Changed: scaled from 72x72 to {px}x{px} and converted to RGB565A8.
 */
"""


def fetch(source: str | None) -> dict[int, Image.Image]:
    """Each emoji's 72x72 PNG, from TWEMOJI_DIR or the pinned release."""
    names = {cp: f"{cp:x}.png" for cp in EMOJI}
    images = {}
    if source:
        folder = Path(source) / "assets" / "72x72"
        for cp, name in names.items():
            images[cp] = Image.open(folder / name)
        return images
    with urllib.request.urlopen(URL) as response:
        data = response.read()
    digest = hashlib.sha256(data).hexdigest()
    if digest != SHA256:
        sys.exit(f"{URL}: SHA-256 {digest}, expected {SHA256}")
    with tarfile.open(fileobj=io.BytesIO(data)) as tar:
        prefix = f"twemoji-{VERSION}/assets/72x72/"
        for cp, name in names.items():
            member = tar.extractfile(prefix + name)
            if member is None:
                sys.exit(f"no {name} in the release")
            images[cp] = Image.open(io.BytesIO(member.read()))
    return images


def rgb565a8(image: Image.Image) -> bytes:
    """The image at PX x PX: RGB565, little-endian, then the alpha plane."""
    small = image.convert("RGBA").convert("RGBa").resize((PX, PX), Image.LANCZOS).convert("RGBA")
    colour, alpha = bytearray(), bytearray()
    for r, g, b, a in small.getdata():
        v = (r >> 3) << 11 | (g >> 2) << 5 | b >> 3
        colour += bytes((v & 0xFF, v >> 8))
        alpha.append(a)
    return bytes(colour + alpha)


def name(cp: int) -> str:
    return unicodedata.name(chr(cp), f"U+{cp:04X}").lower()


def main() -> None:
    codes = sorted(set(EMOJI))
    images = fetch(sys.argv[1] if len(sys.argv) > 1 else None)
    header = LICENSE_NOTE.format(version=VERSION, px=PX)

    h = [header, "#pragma once", "",
         "/* The code points muse_font_emoji_16 draws, in order. */",
         f"#define MUSE_EMOJI_COUNT {len(codes)}",
         "#define MUSE_EMOJI_CODE_POINTS \\"]
    for i in range(0, len(codes), 8):
        row = ", ".join(f"0x{cp:05X}" for cp in codes[i:i + 8])
        h.append(f"    {row}{',' if i + 8 < len(codes) else ''} \\")
    h[-1] = h[-1].removesuffix(" \\")
    (FONTS / "muse_emoji.h").write_text("\n".join(h) + "\n", encoding="utf-8")

    c = [header, '#include "lvgl.h"', '#include "muse_emoji.h"', "",
         f"#define PX {PX}", "",
         "static const uint32_t CODES[MUSE_EMOJI_COUNT] = { MUSE_EMOJI_CODE_POINTS };", "",
         "/* Each glyph's RGB565 pixels, then its alpha. */",
         "static const uint8_t PIXELS[MUSE_EMOJI_COUNT][PX * PX * 3] = {"]
    for cp in codes:
        data = rgb565a8(images[cp])
        c.append(f"    {{   /* U+{cp:04X} {name(cp)} */")
        for i in range(0, len(data), 24):
            c.append("        " + ",".join(f"0x{b:02x}" for b in data[i:i + 24]) + ",")
        c.append("    },")
    c += ["};", "",
          "#define IMAGE(i) { \\",
          "    .header = { .magic = LV_IMAGE_HEADER_MAGIC, .cf = LV_COLOR_FORMAT_RGB565A8, \\",
          "                .w = PX, .h = PX, .stride = PX * 2 }, \\",
          "    .data_size = PX * PX * 3, .data = PIXELS[i] }",
          "",
          "static const lv_image_dsc_t IMAGES[MUSE_EMOJI_COUNT] = {"]
    for i in range(0, len(codes), 8):
        c.append("    " + " ".join(f"IMAGE({j})," for j in range(i, min(i + 8, len(codes)))))
    c += ["};", "",
          "/* An image glyph, two caption cells wide, its bottom on the line's as",
          " * unscii-16's are. Only reads constants, so it's safe off the LVGL task",
          " * (the pager measures captions on the voice task). */",
          "static bool get_glyph_dsc(const lv_font_t *font, lv_font_glyph_dsc_t *dsc, uint32_t letter,",
          "                          uint32_t next)",
          "{",
          "    (void)font;",
          "    (void)next;",
          "    size_t lo = 0, hi = MUSE_EMOJI_COUNT;",
          "    while (lo < hi) {",
          "        size_t mid = (lo + hi) / 2;",
          "        if (CODES[mid] == letter) {",
          "            dsc->adv_w = PX;",
          "            dsc->box_w = PX;",
          "            dsc->box_h = PX;",
          "            dsc->ofs_x = 0;",
          "            dsc->ofs_y = 0;",
          "            dsc->format = LV_FONT_GLYPH_FORMAT_IMAGE;",
          "            dsc->is_placeholder = 0;",
          "            dsc->gid.src = &IMAGES[mid];",
          "            return true;",
          "        }",
          "        if (CODES[mid] < letter) {",
          "            lo = mid + 1;",
          "        } else {",
          "            hi = mid;",
          "        }",
          "    }",
          "    return false;",
          "}",
          "",
          "static const void *get_glyph_bitmap(lv_font_glyph_dsc_t *dsc, lv_draw_buf_t *buf)",
          "{",
          "    (void)buf;",
          "    return dsc->gid.src;   /* the glyph's image */",
          "}",
          "",
          "const lv_font_t muse_font_emoji_16 = {",
          "    .get_glyph_dsc = get_glyph_dsc,",
          "    .get_glyph_bitmap = get_glyph_bitmap,",
          "    .line_height = PX,",
          "    .base_line = 0,",
          "};"]
    (FONTS / "muse_font_emoji_16.c").write_text("\n".join(c) + "\n", encoding="utf-8")
    size = len(codes) * (PX * PX * 3 + 4 + 24)
    print(f"{len(codes)} emoji, about {size // 1024} KB of flash")


if __name__ == "__main__":
    main()
