/*
 * The passcode's platform in the simulator (muse_passcode.h): the record in
 * RAM (a run starts with no passcode, as a gadget fresh from setup), a
 * plain FIPS 180-4 SHA-256, and a fixed salt so renders repeat. A desktop
 * preview only: the gadget's is muse_passcode_esp.c (NVS, PSA, the RNG).
 */

#include <stdint.h>
#include <string.h>

#include "muse_passcode.h"

static muse_pass_rec_t s_rec;
static bool s_have;

bool muse_passcode_platform_load(muse_pass_rec_t *rec)
{
    if (!s_have) return false;
    *rec = s_rec;
    return true;
}

bool muse_passcode_platform_save(const muse_pass_rec_t *rec)
{
    s_rec = *rec;
    s_have = true;
    return true;
}

void muse_passcode_platform_locked(bool locked)
{
    (void)locked;   /* no video view in the simulator */
}

bool muse_passcode_platform_salt(uint8_t salt[MUSE_PASS_SALT_LEN])
{
    for (int i = 0; i < MUSE_PASS_SALT_LEN; i++) salt[i] = (uint8_t)(0x10 + i);
    return true;
}

