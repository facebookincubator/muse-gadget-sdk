/* Dumps the liblc3 v1.1.3 tables needed for 16 kHz (7.5 ms and 10 ms) as Kotlin source.
 * Floats are emitted as raw IEEE-754 bit patterns so the Kotlin port sees bit-identical constants.
 * Build: cc -DLC3_PLUS=0 -DLC3_PLUS_HR=0 -I$LIBLC3/include -I$LIBLC3/src gen_tables.c -o gen_tables
 * Run:   ./gen_tables > ../src/main/kotlin/com/musegadgets/lc3/Lc3Tables.kt */
#include <stdio.h>
#include <string.h>
#include "tables.c"

static unsigned fb(float f) { unsigned u; memcpy(&u, &f, 4); return u; }

static void floats(const char *name, const float *v, int n)
{
    printf("    @JvmField val %s: FloatArray = f(intArrayOf(", name);
    for (int i = 0; i < n; i++) printf("%s%s0x%08x.toInt()", i ? "," : "", i % 6 ? " " : "\n        ", fb(v[i]));
    printf("))\n\n");
}

static void ints(const char *name, const int *v, int n)
{
    int packable = 1;
    for (int i = 0; i < n; i++) if (v[i] < 0 || v[i] > 0xffff) packable = 0;
    if (packable) {
        /* Packed as UTF-16 code units to keep <clinit> small (JVM 64 KB method limit). */
        printf("    @JvmField val %s: IntArray = s(\n        \"", name);
        for (int i = 0; i < n; i++) {
            printf("\\u%04x", v[i]);
            if (i % 16 == 15 && i + 1 < n) printf("\" +\n        \"");
        }
        printf("\")\n\n");
        return;
    }
    printf("    @JvmField val %s: IntArray = intArrayOf(", name);
    for (int i = 0; i < n; i++) printf("%s%s%d", i ? "," : "", i % 12 ? " " : "\n        ", v[i]);
    printf(")\n\n");
}

static void cplx(const char *name, const struct lc3_complex *v, int n)
{
    /* interleaved re, im */
    floats(name, (const float *)v, 2 * n);
}

int main(void)
{
    enum lc3_srate sr = LC3_SRATE_16K;
    printf("%s", "/*\n * Copyright 2022 Google LLC\n * Copyright (c) Meta Platforms, Inc. and affiliates.\n *\n * Licensed under the Apache License, Version 2.0 (the \"License\");\n * you may not use this file except in compliance with the License.\n * You may obtain a copy of the License at\n *\n *     http://www.apache.org/licenses/LICENSE-2.0\n *\n * Unless required by applicable law or agreed to in writing, software\n * distributed under the License is distributed on an \"AS IS\" BASIS,\n * WITHOUT WARRANTIES OR CONDITIONS OF ANY KIND, either express or implied.\n * See the License for the specific language governing permissions and\n * limitations under the License.\n *\n * GENERATED by tools/gen_tables.c from liblc3 v1.1.3 tables.c. Do not edit. Only the 16 kHz entries (7.5 ms and 10 ms) are kept.\n */\n");
    printf("package com.musegadgets.lc3\n\n");
    printf("@Suppress(\"LargeClass\", \"MagicNumber\")\ninternal object Lc3Tables {\n");
    printf("    private fun f(b: IntArray): FloatArray = FloatArray(b.size) { java.lang.Float.intBitsToFloat(b[it]) }\n");
    printf("    private fun s(p: String): IntArray = IntArray(p.length) { p[it].code }\n\n");

    const char *dts[2] = { "7M5", "10M" };
    for (int k = 0; k < 2; k++) {
        enum lc3_dt dt = k == 0 ? LC3_DT_7M5 : LC3_DT_10M;
        int ns = lc3_ns(dt, sr), nd = lc3_nd(dt, sr);
        char nm[64];
        snprintf(nm, sizeof nm, "MDCT_WIN_%s", dts[k]); floats(nm, lc3_mdct_win[dt][sr], ns + nd);
        snprintf(nm, sizeof nm, "MDCT_ROT_%s", dts[k]); cplx(nm, lc3_mdct_rot[dt][sr]->w, lc3_mdct_rot[dt][sr]->n4);
        snprintf(nm, sizeof nm, "BAND_LIM_%s", dts[k]); ints(nm, lc3_band_lim[dt][sr], lc3_num_bands[dt][sr] + 1);
        fprintf(stderr, "dt %s ns %d nd %d n4 %d nb %d\n", dts[k], ns, nd, lc3_mdct_rot[dt][sr]->n4, lc3_num_bands[dt][sr]);
    }

    /* FFT twiddles: bf3 index 0 (n3 = 15 -> "fft 15"), bf2 rows 0..3 of column 0 (10..80) and 0..1 of column 1 (30, 60) */
    printf("    @JvmField val BF3_N3_0: Int = %d\n", lc3_fft_twiddles_bf3[0]->n3);
    floats("BF3_T_0", (const float *)lc3_fft_twiddles_bf3[0]->t, 3 * lc3_fft_twiddles_bf3[0]->n3 * 2 * 2);
    for (int col = 0; col < 2; col++)
        for (int row = 0; row < (col == 0 ? 4 : 2); row++) {
            char nm[64];
            const struct lc3_fft_bf2_twiddles *t = lc3_fft_twiddles_bf2[row][col];
            snprintf(nm, sizeof nm, "BF2_T_%d_%d", row, col);
            printf("    // n2 = %d\n", t->n2);
            cplx(nm, t->t, t->n2);
        }

    floats("SNS_LFCB", &lc3_sns_lfcb[0][0], 32 * 8);
    floats("SNS_HFCB", &lc3_sns_hfcb[0][0], 32 * 8);
    for (int i = 0; i < 4; i++) {
        char nm[32]; snprintf(nm, sizeof nm, "SNS_VQ_GAINS_%d", i);
        floats(nm, lc3_sns_vq_gains[i].v, lc3_sns_vq_gains[i].count);
    }
    {
        int n = sizeof(lc3_sns_mpvq_offsets) / sizeof(lc3_sns_mpvq_offsets[0]);
        ints("SNS_MPVQ_OFFSETS", &lc3_sns_mpvq_offsets[0][0], n * 11);
        fprintf(stderr, "mpvq rows %d\n", n);
    }

    /* Arithmetic coder models: per model 17 symbols x (low, range) */
    {
        int n = sizeof(lc3_tns_order_models) / sizeof(lc3_tns_order_models[0]);
        int v[64 * 34]; int c = 0;
        for (int m = 0; m < n; m++) for (int s = 0; s < 17; s++) v[c++] = lc3_tns_order_models[m].s[s].low, v[c++] = lc3_tns_order_models[m].s[s].range;
        ints("TNS_ORDER_MODELS", v, c);
        n = sizeof(lc3_tns_coeffs_models) / sizeof(lc3_tns_coeffs_models[0]); c = 0;
        for (int m = 0; m < n; m++) for (int s = 0; s < 17; s++) v[c++] = lc3_tns_coeffs_models[m].s[s].low, v[c++] = lc3_tns_coeffs_models[m].s[s].range;
        ints("TNS_COEFFS_MODELS", v, c);
        int b[17 * 8]; c = 0;
        for (int i = 0; i < 2; i++) for (int j = 0; j < 8; j++) b[c++] = lc3_tns_order_bits[i][j];
        ints("TNS_ORDER_BITS", b, c);
        c = 0;
        for (int i = 0; i < 8; i++) for (int j = 0; j < 17; j++) b[c++] = lc3_tns_coeffs_bits[i][j];
        ints("TNS_COEFFS_BITS", b, c);
    }
    {
        int n = sizeof(lc3_spectrum_models) / sizeof(lc3_spectrum_models[0]);
        static int v[1024 * 34]; int c = 0;
        for (int m = 0; m < n; m++) for (int s = 0; s < 17; s++) v[c++] = lc3_spectrum_models[m].s[s].low, v[c++] = lc3_spectrum_models[m].s[s].range;
        ints("SPECTRUM_MODELS", v, c);
        fprintf(stderr, "spectrum models %d\n", n);
        n = sizeof(lc3_spectrum_bits) / sizeof(lc3_spectrum_bits[0]); c = 0;
        for (int m = 0; m < n; m++) for (int s = 0; s < 17; s++) v[c++] = lc3_spectrum_bits[m][s];
        ints("SPECTRUM_BITS", v, c);
        c = 0;
        for (int a = 0; a < 2; a++) for (int b = 0; b < 2; b++) for (int s = 0; s < 256; s++) for (int q = 0; q < 4; q++)
            v[c++] = lc3_spectrum_lookup[a][b][s][q];
        ints("SPECTRUM_LOOKUP", v, c);
    }
    /* LTPF synthesis filters at 16 kHz: w = 4 */
    {
        float v[64]; int c = 0;
        for (int g = 0; g < 4; g++) for (int i = 0; i < 4; i++) v[c++] = lc3_ltpf_cnum[sr][g][i];
        floats("LTPF_CNUM", v, c);
        c = 0;
        for (int p = 0; p < 4; p++) for (int i = 0; i < 4; i++) v[c++] = lc3_ltpf_cden[sr][p][i];
        floats("LTPF_CDEN", v, c);
        fprintf(stderr, "ns_4m[16k] %d ns_2m5 %d ne_2m5 %d\n", lc3_ns_4m[sr], lc3_ns_2m5[sr], lc3_ne_2m5[sr]);
    }
    printf("}\n");
    return 0;
}
