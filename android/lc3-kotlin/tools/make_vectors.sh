# Regenerates the conformance vectors from liblc3 v1.1.3 (the reference the Kotlin port matches bit for bit):
# src/test/resources/vectors/*.lc3 and src/test/kotlin/com/musegadgets/lc3/ReferenceVectors.kt.
# Needs a C compiler, git (or LIBLC3=<liblc3 v1.1.3 checkout>) and kotlinc + java.
set -euo pipefail
here=$(cd "$(dirname "$0")/.." && pwd)
out=$here/build/vectors; mkdir -p "$out"
commit=8e1e722cda8dbdcc4b3cb9ba559d11c236c33d07   # liblc3 v1.1.3, the same commit as xplat/liblc3
lib=${LIBLC3:-$here/build/liblc3}
if [ ! -f "$lib/include/lc3.h" ]; then
    git clone -q https://github.com/google/liblc3 "$lib" && git -C "$lib" checkout -q "$commit"
fi
cc -O2 -ffp-contract=off -U__ARM_NEON -DLC3_PLUS=0 -DLC3_PLUS_HR=0 -I"$lib/include" "$lib"/src/*.c \
    "$here/tools/lc3ref.c" -lm -o "$out/lc3ref"
kotlinc=${KOTLINC:-kotlinc}
"$kotlinc" "$here/src/test/kotlin/com/musegadgets/lc3/TestSignal.kt" "$here/src/test/kotlin/com/musegadgets/lc3/DumpSignal.kt" \
    -include-runtime -d "$out/signal.jar"
java -cp "$out/signal.jar" com.musegadgets.lc3.DumpSignal "$out/signal.raw"
R=$out/lc3ref
h() { shasum -a 256 "$1" | cut -c1-64; }
kt=$here/src/test/kotlin/com/musegadgets/lc3/ReferenceVectors.kt
{
cat <<'HDR'
