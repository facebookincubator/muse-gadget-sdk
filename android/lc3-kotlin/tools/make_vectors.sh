package com.musegadgets.lc3

// GENERATED by tools/make_vectors.sh from liblc3 v1.1.3 (scalar, no FMA contraction). Do not edit.
// SHA-256 of liblc3's output for TestSignal: encoder bitstreams (LTPF off) and decoder PCM (s16le).
internal object ReferenceVectors {
    val SHA256: Map<String, String> = mapOf(
HDR
for dt in 10000 7500; do for nb in 20 30 40 60 100 160 400; do
    t=d${dt}_b${nb}
    $R enc "$out/signal.raw" "$out/$t.lc3" -d $dt -b $nb -l
    $R dec "$out/$t.lc3" "$out/$t.raw" -d $dt -b $nb
    $R dec "$out/$t.lc3" "$out/${t}_P7.raw" -d $dt -b $nb -P 7
    echo "        \"enc_$t\" to \"$(h "$out/$t.lc3")\","
    echo "        \"dec_$t\" to \"$(h "$out/$t.raw")\","
    echo "        \"dec_${t}_P7\" to \"$(h "$out/${t}_P7.raw")\","
done; done
# Streams from liblc3's own encoder with the long-term postfilter on: checked in, they exercise the postfilter.
mkdir -p "$here/src/test/resources/vectors"
for cfg in "10000 40" "7500 30"; do
    set -- $cfg; t=d$1_b$2_ltpf
    $R enc "$out/signal.raw" "$here/src/test/resources/vectors/$t.lc3" -d $1 -b $2
    $R dec "$here/src/test/resources/vectors/$t.lc3" "$out/$t.raw" -d $1 -b $2
    $R dec "$here/src/test/resources/vectors/$t.lc3" "$out/${t}_P7.raw" -d $1 -b $2 -P 7
    $R dec "$here/src/test/resources/vectors/$t.lc3" "$out/${t}_X1.raw" -d $1 -b $2 -X 1
    echo "        \"dec_$t\" to \"$(h "$out/$t.raw")\","
    echo "        \"dec_${t}_P7\" to \"$(h "$out/${t}_P7.raw")\","
    echo "        \"dec_${t}_X1\" to \"$(h "$out/${t}_X1.raw")\","
done
echo "    )"
echo "}"
} > "$kt"
echo "wrote $kt and src/test/resources/vectors/"
