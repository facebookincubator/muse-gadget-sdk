"""LIBLC3=<liblc3 v1.1.3> gen_consts.py: extract function-static float tables from liblc3 sources into Kotlin with C-identical float values
(C: decimal literal -> double -> float). Also checks scalar literals used inline in the Kotlin port."""
import re, struct, os, numpy as np
S = os.path.join(os.environ["LIBLC3"], "src")  # liblc3 v1.1.3 checkout
def c2bits(s):
    s = s.strip().rstrip("fF")
    v = np.float32(np.float64(float.fromhex(s) if "x" in s.lower() else float(s)))
    return struct.unpack("<I", struct.pack("<f", v))[0]
def kparse(s):  # Kotlin float literal: decimal -> nearest float directly
    s = s.strip().rstrip("fF")
    from decimal import Decimal
    import fractions
    fr = fractions.Fraction(Decimal(s))
    # nearest float32 to exact rational
    c = np.float32(float(fr))
    cands = [np.nextafter(c, np.float32(-np.inf)), c, np.nextafter(c, np.float32(np.inf))]
    best = min(cands, key=lambda x: (abs(fractions.Fraction(float(x)) - fr), struct.unpack("<I", struct.pack("<f", x))[0] & 1))
    return struct.unpack("<I", struct.pack("<f", best))[0]
def arr(src, name):
    t = open(f"{S}/{src}").read()
    i = t.index(name); b = t.index("{", i)
    d = 0
    for j in range(b, len(t)):
        if t[j] == "{": d += 1
        elif t[j] == "}":
            d -= 1
            if d == 0: break
    body = re.sub(r"/\*.*?\*/", "", t[b:j+1], flags=re.S)
    return re.findall(r"-?0x[0-9a-fA-F]+p[-+]?[0-9]+|-?[0-9]+\.?[0-9]*(?:[eE][-+]?[0-9]+)?", body)
out = ['/*\n * Copyright 2022 Google LLC\n * Copyright (c) Meta Platforms, Inc. and affiliates.\n *\n * Licensed under the Apache License, Version 2.0 (the "License");\n * you may not use this file except in compliance with the License.\n * You may obtain a copy of the License at\n *\n *     http://www.apache.org/licenses/LICENSE-2.0\n *\n * Unless required by applicable law or agreed to in writing, software\n * distributed under the License is distributed on an "AS IS" BASIS,\n * WITHOUT WARRANTIES OR CONDITIONS OF ANY KIND, either express or implied.\n * See the License for the specific language governing permissions and\n * limitations under the License.\n *\n * GENERATED by tools/gen_consts.py from liblc3 v1.1.3 sources. Do not edit.\n */',
       "package com.musegadgets.lc3", "", "internal object Lc3Consts {",
       "    private fun f(b: IntArray): FloatArray = FloatArray(b.size) { java.lang.Float.intBitsToFloat(b[it]) }", ""]
def emit(kname, vals):
    bits = [c2bits(v) for v in vals]
    rows = [", ".join(f"0x{b:08x}.toInt()" for b in bits[k:k+6]) for k in range(0, len(bits), 6)]
    out.append(f"    @JvmField val {kname}: FloatArray = f(intArrayOf(\n        " + ",\n        ".join(rows) + "))\n")
emit("DCT16_M", arr("sns.c", "dct16_m[16][16]"))
emit("GE_18", arr("sns.c", "ge_18[LC3_MAX_BANDS]"))
emit("IQ_TABLE", arr("spec.c", "iq_table[]"))
emit("TNS_LAG_WINDOW", arr("tns.c", "lag_window[]"))
emit("TNS_Q_THR", arr("tns.c", "q_thr[]"))
emit("TNS_Q_INV", arr("tns.c", "q_inv[]"))
out.append("}")
open(os.path.join(os.path.dirname(os.path.abspath(__file__)), "../src/main/kotlin/com/musegadgets/lc3/Lc3Consts.kt"), "w").write("\n".join(out) + "\n")
# scalar inline literals: check Kotlin direct parse == C double-rounded value
lits = "0.3090169944 -0.8090169944 -0.9510565163 -0.5877852523 1.00000000e+00 1.09050773e+00 1.18920712e+00 1.29683955e+00 1.41421356e+00 1.54221083e+00 1.68179283e+00 1.83400809e+00 1.00448128e-02 5.54563260e-02 2.40228756e-01 6.93147140e-01 -1.29479677 5.11769018 -8.42295281 8.10557963 -3.50567360 31.62277660 199.52623150".split()
bad = [l for l in lits if c2bits(l) != kparse(l)]
print("inline literal mismatches:", bad)
for name, vals in (("dct", arr("sns.c", "dct16_m[16][16]")), ("ge", arr("sns.c", "ge_18[LC3_MAX_BANDS]")), ("iq", arr("spec.c", "iq_table[]"))):
    print(name, len(vals))
