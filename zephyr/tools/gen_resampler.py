"""Generates src/mg_resample_taps.h: the 32 -> 24 kHz (up 3, down 4)
polyphase low-pass for the XIAO's 24 kHz capture.

The nRF54L15's PDM has no exact 24 kHz setting (32 MHz base clock, integer
divisor, fixed ratios, no audio PLL), but 32 kHz is exact (ratio 50,
divisor 20), so the gadget captures at 32 kHz and resamples.

Prototype: a Kaiser-windowed sinc at 96 kHz (the upsampled rate), passband
to 10.5 kHz, stopband from 12 kHz (the 24 kHz output's Nyquist: input
between 12 and 16 kHz would fold to 8-12 kHz), 70 dB. Taps scaled by 3 for
the zero-stuffing. Pure Python: no numpy needed.

  python3 tools/gen_resampler.py > src/mg_resample_taps.h
"""

import math

FS_UP = 96000.0
F_PASS = 10500.0
F_STOP = 12000.0
ATTEN_DB = 70.0
UP = 3


def i0(x):
    s, t, k = 1.0, 1.0, 1
    while t > 1e-12 * s:
        t *= (x / (2 * k)) ** 2
        s += t
        k += 1
    return s


def design():
    dw = 2 * math.pi * (F_STOP - F_PASS) / FS_UP
    n = int(math.ceil((ATTEN_DB - 8) / (2.285 * dw))) + 1
    n += (-n) % UP  # whole taps per phase
    beta = 0.1102 * (ATTEN_DB - 8.7)
    fc = (F_PASS + F_STOP) / 2 / FS_UP  # cycles per sample
    m = (n - 1) / 2.0
    h = []
    for i in range(n):
        x = i - m
        sinc = 2 * fc if x == 0 else math.sin(2 * math.pi * fc * x) / (math.pi * x)
        w = i0(beta * math.sqrt(1 - (x / m) ** 2)) / i0(beta)
        h.append(sinc * w)
    g = sum(h)
    return [UP * v / g for v in h]


def main():
    h = design()
    k = len(h) // UP
    print("/* Generated by tools/gen_resampler.py; do not edit. */")
    print("/* SPDX-License-Identifier: Apache-2.0 */")
    print()
    print("#ifndef MG_RESAMPLE_TAPS_H_")
    print("#define MG_RESAMPLE_TAPS_H_")
    print()
    print(f"/* {len(h)} taps at 96 kHz: pass 0-{F_PASS / 1000:g} kHz, stop from "
          f"{F_STOP / 1000:g} kHz, {ATTEN_DB:g} dB. */")
    print(f"#define MG_RESAMPLE_PHASES {UP}")
    print(f"#define MG_RESAMPLE_TAPS_PER_PHASE {k}")
    print()
    print("/* [phase][tap]: phase p, tap j is prototype tap p + 3 * j. */")
    print("static const float mg_resample_taps[MG_RESAMPLE_PHASES][MG_RESAMPLE_TAPS_PER_PHASE] = {")
    for p in range(UP):
        row = [h[p + UP * j] for j in range(k)]
        print("\t{")
        for i in range(0, k, 6):
            print("\t\t" + " ".join(f"{v:.9e}f," for v in row[i:i + 6]))
        print("\t},")
    print("};")
    print()
    print("#endif")


if __name__ == "__main__":
    main()
