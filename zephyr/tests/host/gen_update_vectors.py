"""mg-update-v2.json (the update prompt) -> a C header for test_gadget.c.

  gen_update_vectors.py <mg-update-v2.json> <out.h>
"""
import hashlib
import importlib.util
import json
import sys
from pathlib import Path

KINDS = {"time": 1, "press": 2, "cancel": 3, "unlock": 4, "reconnect": 5, "injected_press": 6, "forget": 7,
         "set_up": 8}
PROMPTS = {"none": 0, "confirm": 1, "keypad": 2}


def cbor_map(b):
    """The SMP request's CBOR map (text keys; uints, byte/text strings, booleans)."""
    def item(i):
        major, info = b[i] >> 5, b[i] & 31
        i += 1
        if info < 24:
            n = info
        else:
            size = {24: 1, 25: 2, 26: 4, 27: 8}[info]
            n, i = int.from_bytes(b[i:i + size], "big"), i + size
        if major == 0:
            return n, i
        if major in (2, 3):
            v = b[i:i + n]
            return (v if major == 2 else v.decode()), i + n
        if major == 5:
            out = {}
            for _ in range(n):
                k, i = item(i)
                out[k], i = item(i)
            return out, i
        if major == 7:
            return {20: False, 21: True}[info], i
        raise ValueError("unexpected CBOR")
    return item(0)[0] if b else {}


def cbytes(b):
    return "{" + ", ".join("0x%02x" % x for x in b) + "}" if b else "{0}"


def reference(vectors):
    """mg_update_ref.py next to the vectors: its device stands in for the slot (the bytes uploads wrote), which
    the C side's MG_UPD_VERIFY asks about."""
    path = Path(vectors).with_name("mg_update_ref.py")
    spec = importlib.util.spec_from_file_location("mg_update_ref", path)
    mod = importlib.util.module_from_spec(spec)
    sys.dont_write_bytecode = True
    spec.loader.exec_module(mod)
    return mod


def slot_after(slot, body):
    """slot1 once this upload write is in (the reference's write_slot)."""
    s = bytearray(slot)
    off, data = body.get("off", 0), body.get("data", b"")
    if off == 0:
        s = bytearray(body.get("len", len(data)))
    s[off:off + len(data)] = data
    return bytes(s)


def main():
    d = json.load(open(sys.argv[1]))
    ref = reference(sys.argv[1])
    out = ["/* Generated by gen_update_vectors.py from mg-update-v2.json. */\n",
           f"#define UV_PROMPT_MS {d['prompt_timeout_ms']}\n",
           f"#define UV_CONFIRM_MS {d.get('confirm_window_ms', 0)}\n",
           f"#define UV_REARM_MS {d.get('prompt_rearm_ms', 0)}\n"]
    exs = []
    for e, ex in enumerate(d["exchanges"]):
        rows = []
        dev = ref.Device(**ex.get("device", {}))
        for s in ex["steps"]:
            if "smp" in s:
                raw = bytes.fromhex(s["smp"])
                h, body = raw[:8], cbor_map(raw[8:])
                upload = h[0] & 7 == 2 and (h[4] << 8 | h[5], h[7]) == (1, 1)
                # What slot1 holds once this upload write is in, or holds now (anything else): what mg_ota.c
                # hashes for MG_UPD_VERIFY. The request itself goes as it is: the C side reads it.
                slot = slot_after(dev.slot, body) if upload else bytes(dev.slot)
                if dev.smp(raw) != s["rc"]:
                    raise SystemExit(f"{ex['name']}: the reference disagrees with the vectors")
                rows.append("{0, %s, %d, 0, %d, %d, %d, %s}" % (
                    cbytes(raw), len(raw), s["rc"], PROMPTS[s["prompt"]], len(slot),
                    cbytes(hashlib.sha256(slot).digest())))
            else:
                dev.event(s["event"], **({"ms": s["ms"]} if "ms" in s else {}))
                rows.append("{%d, {0}, 0, %d, -1, %d, 0, {0}}" % (KINDS[s["event"]], s.get("ms", 0),
                                                                  PROMPTS[s["prompt"]]))
        out.append("static const struct uv_step uv_steps_%d[] = {\n\t%s,\n};\n" % (e, ",\n\t".join(rows)))
        dv = ex.get("device", {})
        exs.append('{"%s", %d, %d, %d, %d, %d, %d, %d, uv_steps_%d, %d}' % (
            ex["name"].replace('"', "'"), dv.get("release", True), dv.get("holds_token", True),
            dv.get("proof", False), dv.get("console_arm", False), dv.get("button_recovery", False),
            dv.get("self_recovery_unprompted", False), dv.get("locked", False), e, len(rows)))
    out.append("static const struct uv_ex uv_exchanges[] = {\n\t%s,\n};\n" % ",\n\t".join(exs))
    open(sys.argv[2], "w").write("".join(out))


if __name__ == "__main__":
    main()
