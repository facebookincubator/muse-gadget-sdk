"""Turns the repository's published vectors into a C header for test_unit.c.

  gen_vectors.py LINK_PAIRING_V5_JSON TOKEN_PROOF_JSON OUT_H

Everything is emitted as C strings (hex for bytes); the tests decode them.
Standard library only.
"""

import json
import sys


def cstr(s: str) -> str:
    out = []
    for b in s.encode("utf-8"):
        c = chr(b)
        if c == "\\":
            out.append("\\\\")
        elif c == '"':
            out.append('\\"')
        elif c == "\n":
            out.append("\\n")
        elif 0x20 <= b < 0x7F:
            out.append(c)
        else:
            out.append("\\%03o" % b)
    return '"' + "".join(out) + '"'


def main() -> int:
    link_path, proof_path, out_path = sys.argv[1:4]
    link = json.load(open(link_path, encoding="utf-8"))
    proof = json.load(open(proof_path, encoding="utf-8"))
    v = next(x for x in link["vectors"] if x["name"] == "community_v5")
    lines = ["/* Generated by gen_vectors.py from the repository's vectors. */", ""]
    fields = [
        "device_id", "node_id", "mac", "firmware_version", "mobile_private_scalar_hex",
        "device_private_scalar_hex", "mobile_pub", "device_pub", "mobile_nonce", "device_nonce",
        "ecdh_secret_hex", "transcript", "transcript_hash", "session_secret_hex",
        "mobile_tx_key_hex", "mobile_rx_key_hex", "session_id", "client_finished_plaintext",
        "client_finished_aad", "client_finished_ciphertext", "client_finished_tag",
    ]
    for f in fields:
        lines.append("#define V5_%s %s" % (f.upper(), cstr(str(v[f]))))
    lines.append("")
    lines.append("struct tp_vec {")
    lines.append("\tconst char *name, *access, *node, *cn, *dn, *k, *dmac, *cmac;")
    lines.append("\tconst char *challenge, *response, *confirm, *result, *clear;")
    lines.append("};")
    lines.append("static const struct tp_vec TP_VECS[] = {")
    for t in proof["vectors"]:
        fr = t["frames"]
        lines.append("\t{%s, %s, %s, %s, %s, %s, %s, %s," % tuple(cstr(t[k]) for k in (
            "name", "access_token", "node_id", "client_nonce", "device_nonce", "K",
            "device_mac", "client_mac")))
        lines.append("\t %s, %s, %s, %s, %s}," % tuple(cstr(fr[k]) for k in (
            "challenge", "response", "confirm", "result", "clear")))
    lines.append("};")
    lines.append("")
    open(out_path, "w", encoding="utf-8").write("\n".join(lines))
    return 0


if __name__ == "__main__":
    sys.exit(main())
