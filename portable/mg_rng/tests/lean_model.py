"""The lean configuration's seed and generator in Python (src/mg_rng_lean.c), for test_rng_lean.c's known answers:
a record and a sample stream in, the stored record and the first outputs out. Prints a C header."""
import hashlib
import hmac
import struct
import sys

STARTUP, H_MILLI, BITS = 1024, 500, 192
NEED = (BITS * 1000 + H_MILLI - 1) // H_MILLI


def H(k, *p):
    return hmac.new(k, b''.join(p), hashlib.sha256).digest()


def kdf(key, dom, ctr, i):
    return H(key, bytes([ord(dom)]) + struct.pack('<II', ctr, i))


def xorshift(x):
    while True:
        x ^= (x << 13) & 0xFFFFFFFF
        x ^= x >> 17
        x ^= (x << 5) & 0xFFFFFFFF
        yield x


def rec(pool, flags):
    r = b'MGR1' + bytes([flags, 0, 0, 0]) + pool
    return r + kdf(pool, 'c', 0x3152474D, flags)[:4]


def seed(pool, samples):
    """samples: no health failures assumed (a varied stream). Returns (stored record, key)."""
    acc, buf, clean, cnt, pulled = bytes(32), b'', 0, 0, 0
    for raw in samples:
        if cnt >= NEED:
            break
        pulled += 1
        buf += struct.pack('<I', raw)
        if len(buf) == 64:
            acc, buf = H(acc, buf), b''
        if clean < STARTUP:
            clean += 1
        else:
            cnt += 1
    if buf:
        acc = H(acc, buf)
    s = H(b'mgrng lean seed v1', pool, acc, bytes(32), b'', struct.pack('<I', pulled))
    return rec(kdf(s, 'p', 0, 0), 1), kdf(s, 'k', 0, 0)


def generate(key, ctr, n):
    out, i = b'', 0
    while len(out) < n:
        out += kdf(key, 'o', ctr, i)
        i += 1
    return out[:n], kdf(key, 'n', ctr, 0)


def c(name, b):
    return f'static const uint8_t {name}[{len(b)}] = {{' + ', '.join(f'0x{x:02x}' for x in b) + '};'


if __name__ == '__main__':
    pool0 = bytes(range(32))
    g = xorshift(0x2545F491)
    samples = [next(g) for _ in range(STARTUP + NEED + 10)]
    stored, key = seed(pool0, samples)            # a seeded record flagged 1 in, a full count
    o1, key = generate(key, 0, 48)
    o2, key = generate(key, 1, 16)
    print('/* generated by tests/lean_model.py: do not edit */')
    print(c('KA_REC_IN', rec(pool0, 1)))
    print(c('KA_REC_OUT', stored))
    print(c('KA_OUT1', o1))
    print(c('KA_OUT2', o2))
    print(f'#define KA_SEED 0x2545F491u')
